      of a gemstone. It's one of the first tools used in the gem identification process.
    </p>

    <h3 class="text-2xl font-semibold text-purple-700 mb-2">How to Use a Loupe</h3>
    <ul class="list-disc pl-6 text-gray-700 mb-6">
